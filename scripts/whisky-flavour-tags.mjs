// ─── SQL emit ───────────────────────────────────────────────────────────────
function sqlStr(s) { return s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'` }

function emitSchemaAndSeed() {
  const L = []
  L.push(`-- ─────────────────────────────────────────────────────────────────────────
-- Whisky flavour tags — FOUNDATION for the (later) recommendation engine.
-- GENERATED by scripts/whisky-flavour-tags.mjs (emit-sql) — taxonomy is the
-- single source of truth in that file; regenerate, don't hand-edit the seed.
--
-- Two-tier SMWS-style taxonomy (flavour_categories → flavour_descriptors) +
-- whisky_flavour_tags: multi-tag per bottle, both tiers, per-tag confidence,
-- and a confirmed flag (machine proposes, human ratifies — like the MIS
-- preference-candidate queue). Tags AUGMENT whiskies; existing fields untouched.
-- ─────────────────────────────────────────────────────────────────────────

-- Tier 1 — broad flavour families.
create table if not exists flavour_categories (
  slug        text primary key,
  name        text not null,
  description text,
  sort_order  int  not null default 0
);

-- Tier 2 — finer descriptors, each under one category.
create table if not exists flavour_descriptors (
  slug          text primary key,
  category_slug text not null references flavour_categories(slug) on delete cascade,
  name          text not null,
  sort_order    int  not null default 0
);

-- Per-bottle tags. descriptor_slug NULL = a broad-category-only tag.
create table if not exists whisky_flavour_tags (
  id              uuid primary key default gen_random_uuid(),
  whisky_id       uuid not null references whiskies(id) on delete cascade,
  category_slug   text not null references flavour_categories(slug),
  descriptor_slug text references flavour_descriptors(slug),
  confidence      numeric(3,2) not null check (confidence >= 0 and confidence <= 1),
  source          text not null default 'llm',
  model           text,                                  -- provenance: which model proposed it
  evidence        text,                                  -- the prose phrase that supports the tag
  confirmed       boolean not null default false,        -- human-ratified? engine trusts only confirmed
  created_at      timestamptz not null default now(),
  -- one row per (bottle, category, descriptor); NULLS NOT DISTINCT so a bottle
  -- can't get the same broad-only tag twice.
  unique nulls not distinct (whisky_id, category_slug, descriptor_slug)
);
create index if not exists idx_whisky_flavour_tags_whisky    on whisky_flavour_tags(whisky_id);
create index if not exists idx_whisky_flavour_tags_confirmed on whisky_flavour_tags(confirmed);
create index if not exists idx_whisky_flavour_tags_category  on whisky_flavour_tags(category_slug);

-- RLS — mirror whiskies: members read, admins write (reference taxonomy is readable).
alter table flavour_categories   enable row level security;
alter table flavour_descriptors  enable row level security;
alter table whisky_flavour_tags  enable row level security;

drop policy if exists "read flavour_categories" on flavour_categories;
create policy "read flavour_categories" on flavour_categories for select using (auth.uid() is not null);
drop policy if exists "admins write flavour_categories" on flavour_categories;
create policy "admins write flavour_categories" on flavour_categories for all
  using  (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true))
  with check (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true));

drop policy if exists "read flavour_descriptors" on flavour_descriptors;
create policy "read flavour_descriptors" on flavour_descriptors for select using (auth.uid() is not null);
drop policy if exists "admins write flavour_descriptors" on flavour_descriptors;
create policy "admins write flavour_descriptors" on flavour_descriptors for all
  using  (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true))
  with check (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true));

drop policy if exists "read whisky_flavour_tags" on whisky_flavour_tags;
create policy "read whisky_flavour_tags" on whisky_flavour_tags for select using (auth.uid() is not null);
drop policy if exists "admins write whisky_flavour_tags" on whisky_flavour_tags;
create policy "admins write whisky_flavour_tags" on whisky_flavour_tags for all
  using  (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true))
  with check (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.is_admin = true));

-- ── Taxonomy seed (generated from TAXONOMY) ──`)

  for (const c of TAXONOMY) {
    L.push(`insert into flavour_categories (slug, name, description, sort_order) values (${sqlStr(c.slug)}, ${sqlStr(c.name)}, ${sqlStr(c.desc)}, ${c.order})\n  on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;`)
  }
  L.push('')
  for (const c of TAXONOMY) {
    c.descriptors.forEach((d, i) => {
      const name = d.split('_').map(w => w[0].toUpperCase() + w.slice(1)).join(' ')
      L.push(`insert into flavour_descriptors (slug, category_slug, name, sort_order) values (${sqlStr(d + '__' + c.slug)}, ${sqlStr(c.slug)}, ${sqlStr(name)}, ${i})\n  on conflict (slug) do update set category_slug = excluded.category_slug, name = excluded.name, sort_order = excluded.sort_order;`)
    })
  }
  // Note: descriptor slugs are namespaced `<descriptor>__<category>` because the
  // same descriptor word (e.g. vanilla, floral) legitimately appears under more
  // than one category, and the PK must be unique.
  writeFileSync('db/whisky_flavour_tags.sql', L.join('\n') + '\n')
  console.log('wrote db/whisky_flavour_tags.sql')
}

// ─── Calibration tagging ─────────────────────────────────────────────────────
const SB_URL = process.env.NEXT_PUBLIC_SUPABASE_URL
const SB_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY

async function sb(path) {
  const r = await fetch(`${SB_URL}/rest/v1/${path}`, {
    headers: { apikey: SB_KEY, Authorization: `Bearer ${SB_KEY}` },
  })
  if (!r.ok) throw new Error(`supabase ${r.status}: ${await r.text()}`)
  return r.json()
}

function vocabForPrompt() {
  return TAXONOMY.map(c =>
    `- ${c.slug} — "${c.name}": ${c.desc}\n    descriptors: ${c.descriptors.join(', ')}`
  ).join('\n')
}

const TOOL = {
  name: 'emit_flavour_tags',
  description: 'Emit the flavour tags supported by the tasting notes.',
  input_schema: {
    type: 'object',
    properties: {
      notes_quality: { type: 'string', enum: ['rich', 'thin', 'none'],
        description: 'rich = real flavour prose; thin = a little but sparse; none = no flavour info (empty, or just a region/operational note).' },
      tags: {
        type: 'array',
        items: {
          type: 'object',
          properties: {
            category_slug:   { type: 'string', description: 'MUST be one of the taxonomy category slugs.' },
            descriptor_slug: { type: ['string', 'null'], description: 'A descriptor under that category, or null for a broad-only tag. Bare descriptor word (e.g. "vanilla"), not namespaced.' },
            confidence:      { type: 'number', description: '0..1 — how explicitly the PROSE supports this tag. 0.9+ stated outright; 0.6-0.8 clearly implied; <0.5 weak/borderline.' },
            evidence:        { type: 'string', description: 'The exact phrase from the tasting notes that supports this tag.' },
          },
          required: ['category_slug', 'descriptor_slug', 'confidence', 'evidence'],
        },
      },
      comment: { type: 'string', description: 'One short line: how confident/shaky this was, or any taxonomy gap hit.' },
    },
    required: ['notes_quality', 'tags', 'comment'],
  },
}

function systemPrompt() {
  return `You tag whisky flavour profiles for The Rampant Club, against a FIXED two-tier taxonomy.

CONTROLLED VOCABULARY (tag ONLY against these — never invent a category or descriptor):
${vocabForPrompt()}

ABSOLUTE RULES:
1. Tag ONLY flavours explicitly present in the TASTING NOTES prose you are given. For every tag, the "evidence" must be an actual phrase from those notes.
2. NEVER infer flavour from the whisky's name, distillery, region, or age. "It's a Speyside so probably fruity" is FORBIDDEN — that is fabricated data. The name is given only so you know what you're reading; it is NOT a source of tags.
3. If the notes are empty, or contain no flavour information (e.g. just "Ireland", or an operational note like "broken while sorting"), return notes_quality "none" and an EMPTY tags array. Producing nothing is the correct answer for a bottle with no flavour prose.
4. Prefer a broad category tag (descriptor_slug = null) when the prose is general; add a descriptor when the prose names a specific note that maps to one. A bottle may carry several categories and several descriptors.
5. descriptor_slug must belong to the category_slug you pair it with. Use the bare descriptor word.
6. confidence reflects how directly the prose supports the tag — be honest; low confidence is fine and useful (it flags the tag for human review).`
}

async function tagOne(anthropic, w) {
  const userText = `WHISKY NAME (reference only — do NOT tag from this): ${w.name}\n\nTASTING NOTES (tag ONLY from this prose):\n"""\n${(w.tasting_notes || '').trim() || '(no notes)'}\n"""`
  const msg = await anthropic.messages.create({
    model: MODEL,
    max_tokens: 1200,
    system: systemPrompt(),
    tools: [TOOL],
    tool_choice: { type: 'tool', name: 'emit_flavour_tags' },
    messages: [{ role: 'user', content: userText }],
  })
  const tool = msg.content.find(c => c.type === 'tool_use')
  if (!tool) throw new Error('no tool_use in response')
  return tool.input
}

function pickCalibration(all) {
  const len = w => (w.tasting_notes || '').trim().length
  const byName = (a, b) => a.name.localeCompare(b.name)
  const rich = all.filter(w => len(w) >= 180).sort(byName)
  const thin = all.filter(w => len(w) > 0 && len(w) < 180).sort(byName)
  const empty = all.filter(w => len(w) === 0).sort(byName)

  // Spread the rich bottles across the alphabet (even stride → variety of
  // distilleries/styles), then make sure some peated examples are in.
  const want = 24
  const stride = Math.max(1, Math.floor(rich.length / want))
  const richPick = []
  for (let i = 0; i < rich.length && richPick.length < want; i += stride) richPick.push(rich[i])
  const peatRe = /(peat|smoke|smoky|iodine|medicinal|brine|seaweed|maritime|coastal|tar|bonfire)/i
  for (const w of rich) {
    if (richPick.length >= want + 4) break
    if (peatRe.test(w.tasting_notes) && !richPick.includes(w)) richPick.push(w)
  }
  const thinPick  = thin.slice(0, 8)
  const emptyPick = empty.filter((_, i) => i % Math.max(1, Math.floor(empty.length / 8)) === 0).slice(0, 8)
  return { richPick, thinPick, emptyPick }
}

async function runTagging() {
  const apiKey = process.env.ANTHROPIC_API_KEY
  if (!apiKey) throw new Error('ANTHROPIC_API_KEY not set')
  if (!SB_URL || !SB_KEY) throw new Error('Supabase env not set')
  const anthropic = new Anthropic({ apiKey })

  const all = await sb('whiskies?select=id,name,region,age,tasting_notes&order=name')
  const { richPick, thinPick, emptyPick } = pickCalibration(all)
  const batch = [
    ...richPick.map(w => ({ ...w, bucket: 'rich' })),
    ...thinPick.map(w => ({ ...w, bucket: 'thin' })),
    ...emptyPick.map(w => ({ ...w, bucket: 'empty' })),
  ]
  console.log(`calibration batch: ${batch.length} (rich ${richPick.length}, thin ${thinPick.length}, empty ${emptyPick.length})`)

  const results = []
  for (const w of batch) {
    let out, err = null
    for (let attempt = 0; attempt < 2 && !out; attempt++) {
      try { out = await tagOne(anthropic, w) }
      catch (e) { err = e.message; await new Promise(r => setTimeout(r, 800)) }
    }
    if (!out) { console.log(`  ✗ ${w.name.slice(0,40)} — ${err}`); results.push({ ...w, error: err, tags: [] }); continue }
    // validate against vocab — drop anything off-taxonomy (and record it)
    const clean = [], rejected = []
    for (const t of (out.tags || [])) {
      const cat = CAT_BY_SLUG[t.category_slug]
      if (!cat) { rejected.push({ ...t, why: 'unknown category' }); continue }
      if (t.descriptor_slug && !cat.descriptors.includes(t.descriptor_slug)) { rejected.push({ ...t, why: 'descriptor not in category' }); continue }
      clean.push({ category_slug: t.category_slug, descriptor_slug: t.descriptor_slug || null,
                   confidence: Math.round(Math.max(0, Math.min(1, t.confidence)) * 100) / 100, evidence: t.evidence })
    }
    results.push({ id: w.id, name: w.name, region: w.region, age: w.age, bucket: w.bucket,
                   tasting_notes: w.tasting_notes || '', notes_quality: out.notes_quality,
                   comment: out.comment, tags: clean, rejected })
    console.log(`  ✓ ${w.bucket.padEnd(5)} ${w.name.slice(0,42).padEnd(42)} → ${clean.length} tags (${out.notes_quality})`)
  }

  writeFileSync('data/whisky_flavour_calibration.json', JSON.stringify(results, null, 2) + '\n')
  writeCalibrationSql(results)
  writeReport(results)
  console.log('\nwrote data/whisky_flavour_calibration.json, db/whisky_flavour_calibration_tags.sql, docs/whisky_flavour_calibration_report.md')
}

function writeCalibrationSql(results) {
  const L = [`-- Calibration-batch flavour tags (Phase 1) — confirmed=false, nothing auto-trusted.
-- GENERATED by scripts/whisky-flavour-tags.mjs. Run db/whisky_flavour_tags.sql FIRST.
-- descriptor slug is namespaced <descriptor>__<category> to match the seed PKs.`]
  let n = 0
  for (const r of results) {
    if (!r.tags?.length) continue
    L.push(`-- ${r.name.replace(/\n/g, ' ')}  [${r.bucket}]`)
    for (const t of r.tags) {
      const desc = t.descriptor_slug ? sqlStr(t.descriptor_slug + '__' + t.category_slug) : 'null'
      L.push(`insert into whisky_flavour_tags (whisky_id, category_slug, descriptor_slug, confidence, source, model, evidence, confirmed) values (${sqlStr(r.id)}, ${sqlStr(r.category_slug || t.category_slug)}, ${desc}, ${t.confidence}, 'llm', ${sqlStr(MODEL)}, ${sqlStr((t.evidence||'').slice(0,300))}, false)\n  on conflict (whisky_id, category_slug, descriptor_slug) do nothing;`)
      n++
    }
  }
  L.unshift(`-- ${n} tags across ${results.filter(r=>r.tags?.length).length} bottles.`)
  writeFileSync('db/whisky_flavour_calibration_tags.sql', L.join('\n') + '\n')
}

function writeReport(results) {
  const byBucket = b => results.filter(r => r.bucket === b)
  const richTagged = byBucket('rich').filter(r => r.tags?.length).length
  const thinTagged = byBucket('thin').filter(r => r.tags?.length).length
  const emptyTagged = byBucket('empty').filter(r => r.tags?.length).length
  const allTags = results.flatMap(r => r.tags || [])
  const avgConf = allTags.length ? (allTags.reduce((s,t)=>s+t.confidence,0)/allTags.length) : 0
  const rejected = results.flatMap(r => (r.rejected||[]).map(x => ({ name: r.name, ...x })))

  const L = []
  L.push(`# Whisky flavour-tagging — Phase 1 calibration report\n`)
  L.push(`Model: \`${MODEL}\` · taxonomy: SMWS-style two-tier (12 categories) · all tags \`confirmed=false\`.\n`)
  L.push(`## Summary`)
  L.push(`- Calibration batch: **${results.length}** bottles — rich ${byBucket('rich').length}, thin ${byBucket('thin').length}, empty ${byBucket('empty').length}.`)
  L.push(`- **Rich** notes that produced tags: **${richTagged}/${byBucket('rich').length}**.`)
  L.push(`- **Thin** notes that produced tags: **${thinTagged}/${byBucket('thin').length}** (expect ~0 — thin = region/operational only).`)
  L.push(`- **Empty** notes that produced tags: **${emptyTagged}/${byBucket('empty').length}** (MUST be 0 — any tag here = hallucination).`)
  L.push(`- Total tags: **${allTags.length}**, average confidence **${avgConf.toFixed(2)}**.`)
  L.push(`- Off-taxonomy tags rejected by the validator: **${rejected.length}**.\n`)
  if (rejected.length) { L.push(`### ⚠ Off-taxonomy attempts (rejected, not written):`); for (const x of rejected) L.push(`- ${x.name}: \`${x.category_slug}/${x.descriptor_slug}\` — ${x.why}`); L.push('') }

  for (const bucket of ['rich', 'thin', 'empty']) {
    L.push(`\n## ${bucket.toUpperCase()} notes\n`)
    for (const r of byBucket(bucket)) {
      L.push(`### ${r.name}`)
      L.push(`*${r.region || '—'}${r.age ? ' · ' + r.age : ''} · model says notes are "${r.notes_quality || (r.error ? 'ERROR' : '—')}"*`)
      if (r.error) L.push(`> ⚠ error: ${r.error}`)
      L.push(`\n> **Notes:** ${r.tasting_notes ? r.tasting_notes.replace(/\n/g,' ') : '_(none)_'}\n`)
      if (!r.tags?.length) { L.push(`**Tags:** _none_${bucket==='empty'||bucket==='thin' ? ' ✓ (correctly no hallucination)' : ''}\n`) }
      else {
        L.push(`**Tags:**`)
        for (const t of r.tags) {
          const cat = CAT_BY_SLUG[t.category_slug]?.name || t.category_slug
          L.push(`- **${cat}**${t.descriptor_slug ? ' › ' + t.descriptor_slug : ''} — \`${t.confidence.toFixed(2)}\` · _“${t.evidence}”_`)
        }
        L.push('')
      }
      if (r.comment) L.push(`_model note: ${r.comment}_\n`)
    }
  }
  writeFileSync('docs/whisky_flavour_calibration_report.md', L.join('\n') + '\n')
}

// ─── main ────────────────────────────────────────────────────────────────────
const cmd = process.argv[2]
if (cmd === 'emit-sql') emitSchemaAndSeed()
else if (cmd === 'tag') runTagging().catch(e => { console.error(e); process.exit(1) })
else { console.error('usage: node scripts/whisky-flavour-tags.mjs [emit-sql|tag]'); process.exit(1) }
